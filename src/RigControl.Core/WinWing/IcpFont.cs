/// pantalla va en celdas de 8x13: 25 columnas x 5 filas.
/// </summary>
public static class IcpFont
{
    public const int CharWidth = 8;
    public const int CharHeight = 13;
    public const int Columns = IcpDisplay.Width / CharWidth;   // 25
    public const int Rows = IcpDisplay.Height / CharHeight;    // 5

    /// <summary>Carácter de cada glifo, en orden ('\0' = sin carácter; el último es el de "desconocido").
    /// '↕' = flecha arriba/abajo de la DED, '°' = grado, '*' = asterisco de la DED.</summary>
    private const string Chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ1234567890↕()<>[]+-*/=°|~\0.,!?:;&_'\"%#@{} \0\0\0";
    private const int Unknown = 71;

    private static readonly Dictionary<char, int> Index = BuildIndex();

    private static Dictionary<char, int> BuildIndex()
    {
        var d = new Dictionary<char, int>();
        for (var i = 0; i < Chars.Length; i++) if (Chars[i] != '\0') d[Chars[i]] = i;
        d['º'] = d['°']; d['^'] = d['°'];
        return d;
    }

    /// <summary>Filas del glifo de un carácter (minúsculas = mayúsculas; desconocido = trama).</summary>
    public static ReadOnlySpan<byte> Glyph(char c)
    {
        if (!Index.TryGetValue(c, out var i) && !Index.TryGetValue(char.ToUpperInvariant(c), out i)) i = Unknown;
        return Glyphs.AsSpan(i * CharHeight, CharHeight);
    }

    public static bool CanDraw(char c) => Index.ContainsKey(c) || Index.ContainsKey(char.ToUpperInvariant(c));

